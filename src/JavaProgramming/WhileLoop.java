package JavaProgramming;

public class WhileLoop {
    public static void main(String[] args) {
        int i = 1;
        while (i <= 10) {
            System.out.println(i);
            i++;
        }
            System.out.println("--------------");
        for (int j = 0; j <10 ; j=j+1) {
            System.out.println(j);
        }
            System.out.println("--------------");
        for (int k = 10; k >0 ; k--) {
            System.out.println(k);

        }
    }
}
